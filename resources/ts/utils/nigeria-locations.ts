/** Returns a state only when a location name identifies exactly one state. */
export const stateForLocation = (location: string): NigeriaState | undefined => {
  const normalized = location.trim().toLocaleLowerCase()
  if (!normalized) return undefined

  const matches = nigeriaStates.filter(
    state =>
      state.capital.toLocaleLowerCase() === normalized ||
      state.lgas.some(lga => lga.toLocaleLowerCase() === normalized),
  )

  return matches.length === 1 ? matches[0] : undefined
}
